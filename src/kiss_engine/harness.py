def baseline_count(a, b, lower, upper):
    """Sort + bisect reference: the behaviour a candidate has to beat."""
    if upper < lower:
        return 0
    sorted_b = sorted(b)
    total = 0
    for x in a:
        total += bisect.bisect_right(sorted_b, upper - x) - bisect.bisect_left(sorted_b, lower - x)
    return total


def handle_batch(fn, cases):
    if not isinstance(cases, list):
        return {"ok": False, "error": "cases must be a list", "error_type": "protocol_error"}
    if len(cases) > MAX_CASES_PER_BATCH:
        return {"ok": False, "error": "batch of %d cases exceeds %d" % (len(cases), MAX_CASES_PER_BATCH),
                "error_type": "protocol_error"}
    results = []
    for case in cases:
        if not isinstance(case, list) or len(case) != 4:
            results.append({"error": "case must be [a, b, lower, upper]", "error_type": "protocol_error"})
            continue
        a, b, lower, upper = case
        if not isinstance(a, list) or not isinstance(b, list):
            results.append({"error": "a and b must be lists", "error_type": "protocol_error"})
            continue
        if len(a) > MAX_ARRAY_LEN or len(b) > MAX_ARRAY_LEN:
            results.append({"error": "array longer than %d" % MAX_ARRAY_LEN, "error_type": "protocol_error"})
            continue
        try:
            copy_a, copy_b = list(a), list(b)
            value = fn(copy_a, copy_b, int(lower), int(upper))
            if copy_a != a or copy_b != b:
                raise ValueError("candidate mutated caller inputs")
        except BaseException as exc:
            results.append({"error": "%s: %s" % (type(exc).__name__, exc), "error_type": "test_failure"})
            continue
        results.append({"value": value})
    return {"ok": True, "results": results}


def time_calls(fn, a, b, lower, upper, reps):
    """Time ``reps`` calls, each on its own copy of both inputs."""
    samples = []
    for _ in range(reps):
        copy_a = list(a)
        copy_b = list(b)
        started = time.perf_counter()
        fn(copy_a, copy_b, lower, upper)
        samples.append((time.perf_counter() - started) * 1000.0)
    return samples


