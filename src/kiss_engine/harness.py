class WorkerChannel:
    """Bounded newline-JSON transport to the unprivileged worker."""

    def __init__(self, proc):
        self.proc = proc
        self.fd = proc.stdout.fileno()
        self.buffer = b""
        self.total_bytes = 0

    def send(self, payload, deadline):
        """Deadline-bounded write: a slow candidate must not block the supervisor.

        Chunks are capped at PIPE_BUF so a writable pipe never partially blocks.
        """
        data = (json.dumps(payload, separators=(",", ":")) + "\\n").encode("utf-8")
        if len(data) > MAX_REQUEST_BYTES:
            raise ProtocolFailure("request of %d bytes exceeds cap %d" % (len(data), MAX_REQUEST_BYTES))
        fd = self.proc.stdin.fileno()
        view = memoryview(data)
        while view:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                raise TimeoutFailure("worker did not accept the request before its deadline")
            _, writable, _ = select.select([], [fd], [], remaining)
            if not writable:
                raise TimeoutFailure("worker did not accept the request before its deadline")
            try:
                written = os.write(fd, view[:4096])
            except (BrokenPipeError, OSError) as exc:
                raise ProtocolFailure("worker stdin closed: %s" % exc)
            if written <= 0:
                raise ProtocolFailure("worker stdin closed")
            view = view[written:]

    def _fill(self, deadline):
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            raise TimeoutFailure("worker produced no output before its deadline")
        ready, _, _ = select.select([self.fd], [], [], remaining)
        if not ready:
            raise TimeoutFailure("worker produced no output before its deadline")
        chunk = os.read(self.fd, 65536)
        if not chunk:
            raise ProtocolFailure("worker closed the protocol channel unexpectedly")
        self.total_bytes += len(chunk)
        if self.total_bytes > MAX_TOTAL_BYTES:
            raise ProtocolFailure("worker output exceeded %d bytes" % MAX_TOTAL_BYTES)
        self.buffer += chunk

    def read_line(self, deadline):
        while b"\\n" not in self.buffer:
            if len(self.buffer) > MAX_LINE_BYTES:
                raise ProtocolFailure("worker line exceeded %d bytes" % MAX_LINE_BYTES)
            self._fill(deadline)
        line, _, self.buffer = self.buffer.partition(b"\\n")
        if len(line) > MAX_LINE_BYTES:
            raise ProtocolFailure("worker line exceeded %d bytes" % MAX_LINE_BYTES)
        return line

    def read_message(self, deadline):
        """Read one JSON object line sent by the worker (no request involved)."""
        line = self.read_line(deadline)
        try:
            message = json.loads(line.decode("utf-8"))
        except Exception as exc:
            raise ProtocolFailure("worker sent invalid JSON: %s" % exc)
        if not isinstance(message, dict):
            raise ProtocolFailure("worker message is not a JSON object")
        return message

    def request(self, payload, deadline):
        self.send(payload, deadline)
        return self.read_message(deadline)


class Clock:
    """Single wall-clock budget shared by every phase."""

    def __init__(self, budget):
        self.start = time.monotonic()
        self.deadline = self.start + budget

    def at(self, cap):
        return min(time.monotonic() + cap, self.deadline)

    def remaining(self):
        return self.deadline - time.monotonic()


