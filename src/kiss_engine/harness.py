def build_harness(seed: int, benchmark_n: int = DEFAULT_BENCHMARK_N) -> str:
    """Build the trusted root supervisor source for ``seed`` and ``benchmark_n``.

    Pure string building: no filesystem access, no candidate import, no execution.
    """
    if isinstance(seed, bool) or not isinstance(seed, int):
        raise TypeError(f"seed must be an int, got {type(seed).__name__}")
    if isinstance(benchmark_n, bool) or not isinstance(benchmark_n, int):
        raise TypeError(f"benchmark_n must be an int, got {type(benchmark_n).__name__}")
    if seed < 0:
        raise ValueError("seed must be >= 0")
    if benchmark_n < 1 or benchmark_n > MAX_BENCHMARK_N:
        raise ValueError(
            f"benchmark_n must be in [1, {MAX_BENCHMARK_N}], got {benchmark_n}"
        )
    replacements = {
        "__PROTOCOL_VERSION__": str(PROTOCOL_VERSION),
        "__SEED__": str(seed),
        "__BENCHMARK_N__": str(benchmark_n),
        "__TOTAL_TESTS__": str(TOTAL_TESTS),
        "__BENCH_GEN_SOURCE__": _BENCH_GEN_SOURCE,
        "__WORKER_SOURCE_LITERAL__": repr(build_worker_source()),
    }
    return _substitute(_SUPERVISOR_TEMPLATE, replacements)


def _substitute(template: str, replacements: dict) -> str:
    source = template
    for placeholder, value in replacements.items():
        count = source.count(placeholder)
        if count != 1:
            raise AssertionError(
                f"placeholder {placeholder} occurs {count} times, expected 1"
            )
        source = source.replace(placeholder, value)
    return source


def parse_result(stdout_text: str) -> dict:
    """Parse and validate the single JSON result line produced by the supervisor.

    Scans from the end so stray log lines cannot hide the result. Raises
    ``ValueError`` when the contract is violated (wrong protocol version, unknown
    status, more than two counterexamples, out-of-range counters) and ``TypeError``
    when a field has the wrong type.
    """
    if not isinstance(stdout_text, str):
        raise TypeError(f"stdout_text must be str, got {type(stdout_text).__name__}")
    for line in reversed(stdout_text.splitlines()):
        stripped = line.strip()
        if not stripped.startswith("{"):
            continue
        try:
            payload = json.loads(stripped)
        except json.JSONDecodeError:
            continue
        if isinstance(payload, dict):
            return _validate_result(payload)
    raise ValueError("no JSON result object found in harness stdout")


def _validate_result(payload: dict) -> dict:
    version = payload.get("protocol_version")
    if type(version) is not int or version != PROTOCOL_VERSION:
        raise ValueError(f"protocol_version {version!r} != {PROTOCOL_VERSION}")
    status = payload.get("status")
    if status not in STATUS_VALUES:
        raise ValueError(
            f"unknown status {status!r}, expected one of {sorted(STATUS_VALUES)}"
        )
    passed = payload.get("tests_passed")
    total = payload.get("total")
    if isinstance(passed, bool) or not isinstance(passed, int):
        raise TypeError(f"tests_passed must be an int, got {passed!r}")
    if isinstance(total, bool) or not isinstance(total, int):
        raise TypeError(f"total must be an int, got {total!r}")
    if total < 0 or passed < 0 or passed > total:
        raise ValueError(f"tests_passed {passed} out of range for total {total}")
    if total != TOTAL_TESTS:
        raise ValueError("unexpected test suite total")
    if status in {"correct", "performance_met"} and (
        passed != TOTAL_TESTS or payload.get("compile_ok") is not True
    ):
        raise ValueError("success requires the complete suite and compile_ok")
    errors = payload.get("errors")
    if not isinstance(errors, list):
        raise TypeError(f"errors must be a list, got {type(errors).__name__}")
    if len(errors) > MAX_ERRORS:
        raise ValueError(
            f"errors holds {len(errors)} entries, at most {MAX_ERRORS} allowed"
        )
    for key in ("candidate_ms", "baseline_ms"):
        value = payload.get(key)
        if value is None:
            continue
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise TypeError(f"{key} must be null or a number, got {value!r}")
        if value is not None and (not math.isfinite(value) or value <= 0):
            raise ValueError(f"{key} must be finite and positive")
    benchmark = payload.get("benchmark")
    if benchmark is not None and not isinstance(benchmark, dict):
        raise TypeError(
            f"benchmark must be null or an object, got {type(benchmark).__name__}"
        )
    if status in ("correct", "performance_met"):
        if (
            benchmark is None
            or errors
            or payload.get("candidate_ms") is None
            or payload.get("baseline_ms") is None
        ):
            raise ValueError(
                "successful verdict requires benchmark, valid times, no errors"
            )
        for key in (
            "n",
            "reps",
            "warmup",
            "candidate_count",
            "baseline_count",
            "expected_count",
        ):
            if key not in benchmark:
                raise ValueError(f"benchmark block is missing {key!r}")
        counts = [
            benchmark[k]
            for k in ("candidate_count", "baseline_count", "expected_count")
        ]
        if any(type(x) is not int for x in counts) or len(set(counts)) != 1:
            raise ValueError("benchmark counts must be equal integers")
    return payload


def extract_worker_source(harness_source: str) -> str:
    """Recover the embedded worker script from generated supervisor source (AST only)."""
    import ast

    tree = ast.parse(harness_source)
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == "WORKER_SOURCE"
            for target in node.targets
        ):
            value = ast.literal_eval(node.value)
            if not isinstance(value, str):
                raise ValueError("WORKER_SOURCE is not a string literal")
            return value
    raise ValueError("WORKER_SOURCE assignment not found")


