def brute_count_pairs(a, b, lower, upper):
    """O(n*m) inclusive count, written independently of any candidate or bisect."""
    total = 0
    for x in a:
        for y in b:
            if lower <= x + y <= upper:
                total += 1
    return total


def fast_count_pairs(a, b, lower, upper):
    """O((n+m) log m) inclusive count used to validate the benchmark result."""
    if upper < lower:
        return 0
    sorted_b = sorted(b)
    total = 0
    for x in a:
        total += bisect.bisect_right(sorted_b, upper - x) - bisect.bisect_left(sorted_b, lower - x)
    return total


